"""Non-destructive presentation-only cleanup for Texas Sales Tax Monitor.

Run from repository root: python polish_dashboard.py
Backs up index.html and updates only markup, copy and CSS.
It does not modify JavaScript data loaders, chart logic, CSVs, or workflows.
"""
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parent
# Script may be copied into repository root or run directly from package elsewhere.
INDEX = Path.cwd() / 'index.html'
if not INDEX.exists():
    raise SystemExit('Run this script inside the texas-sales-tax-monitor repository (index.html not found).')
s = INDEX.read_text(encoding='utf-8')
MARKER = 'TEXAS_SALES_TAX_POLISH_V1'
if MARKER in s:
    raise SystemExit('Polish already applied; no changes made.')
for marker in ('id="historical-module"', 'id="local-module"', 'id="history-chart"', 'id="local-rows"'):
    if marker not in s:
        raise SystemExit(f'Expected element {marker} not found. No files changed.')

# Remove abandoned placeholder cards, not actual data interfaces.
start = s.find('<div class="section cols"><section class="card"><h2>City &amp; county explorer</h2>')
if start < 0:
    start = s.find('<div class="section cols"><section class="card"><h2>City & county explorer</h2>')
if start >= 0:
    end = s.find('<div class="section card"><h2>Methods, definitions &amp; sources</h2>', start)
    if end < 0:
        end = s.find('<div class="section card"><h2>Methods, definitions & sources</h2>', start)
    if end < 0:
        raise SystemExit('Could not safely delimit placeholder panels. No files changed.')
    s = s[:start] + s[end:]

# Targeted copy: replace original visible content without changing IDs or handlers.
substitutions = [
 ('Historical industry time series', 'Historical Sales Tax by Industry'),
 ('Import a normalized export of official monthly NAICS receipts. Trends and YoY growth are calculated from actual rows only.',
  'Explore monthly Texas sales tax receipts by industry and retail subsector.'),
 ('City-level monthly allocations explorer', 'Monthly City Sales Tax Allocations'),
 ('Import the CSV generated by <code>fetch_local.py</code>. County selections aggregate cities assigned to that county; they do not represent the county government\'s revenue or total county taxable sales.',
  'Explore monthly sales tax revenue distributed to Texas municipalities. County selections group municipalities by their reported county.'),
 ('Monthly municipal sales tax allocations (payment month). These are not taxable sales or county revenue.',
  'Compare municipal sales tax allocations across cities over time. Values reflect payment month.'),
 ('Latest selected observation', 'Latest monthly receipts'),
 ('True year-over-year growth', 'Year-over-year growth'),
 ('Calculated from the same sector exactly 12 months earlier; not interpolated.',
  'Versus the same month one year earlier.'),
 ('Historical files are read locally by your browser; nothing is uploaded to a server. The historical mode does not substitute for Comptroller reporting and should preserve original file vintages.',
  'Source: Texas Comptroller. Reported net receipts may be revised.'),
 ('Monthly allocation values may include corrections and tax-rate changes. YoY growth is computed from the reported comparable prior-year payment, not an economic activity month.',
  'Source: Texas Comptroller. Payment-month allocations may include adjustments and tax-rate changes.'),
 ('Click column headers to sort. Retail subsectors overlap with the Retail Trade industry; do not sum industry and retail tables together.',
  'Sort by industry, receipts, or growth. Retail subsectors are already included in Retail Trade.'),
 ('Analytical groupings (not official consumption classifications)',
  'Broad analytical groupings of receipts by taxpayer industry'),
]
for old, new in substitutions:
    if old in s:
        s = s.replace(old, new)

# Shorten or eliminate outdated static import instructions. Dynamic status remains intact.
s = re.sub(r'(<div id="history-msg" class="status">).*?(</div>)',
           r'\1Official monthly history loads automatically.\2', s, count=1, flags=re.S)
s = re.sub(r'(<div id="local-msg" class="status">).*?(</div>)',
           r'\1Municipal allocation history loads automatically.\2', s, count=1, flags=re.S)
# Keep file inputs in DOM to preserve upload-handler compatibility; hide only in main UI.
# Removes stale controls and status pill; provides clear hierarchy for active selectors.
css = r'''
<style id="TEXAS_SALES_TAX_POLISH_V1">
/* Presentation only. Import elements and their listeners stay in the DOM. */
#historical-module label[for="historical-file"],
#historical-module #historical-file,
#historical-module #reset-history,
#historical-module #history-state,
#local-module label[for="local-file"],
#local-module #local-file { display:none !important; }
#historical-module .hero, #local-module { min-width:0; }
#historical-module .import-row, #local-module .import-row { gap:12px; margin:16px 0 10px; }
#historical-module select, #local-module select {
  min-height:42px; border-radius:10px; background:#fff;
  border:1px solid #ccd6e4; padding:8px 12px; color:#24334b;
}
#historical-module .status, #local-module .status { font-size:12px; color:#697993; }
#historical-module .note { padding:9px 12px; margin-top:16px; font-size:12px; border-left:2px solid #d8e2ef; background:#f8fafc; }
#historical-module .three-cols { gap:24px; }
#historical-module h2, #local-module h2 { letter-spacing:-.02em; }
#local-module .local-table { border-radius:9px; overflow:auto; }
#local-module td.num, #local-module th.num { text-align:right; font-variant-numeric:tabular-nums; }
#local-module tbody tr:hover { background:#f8fafc; }
@media(max-width:640px) {
 #historical-module select, #local-module select { max-width:100%; width:100%; }
 #historical-module .import-row, #local-module .import-row { display:flex; flex-direction:column; align-items:stretch; }
}
</style>
'''
if '</head>' not in s:
    raise SystemExit('Missing </head> tag. No files changed.')
s = s.replace('</head>', css + '</head>', 1)

backup = INDEX.with_name('index.html.before-polish')
if backup.exists():
    raise SystemExit('Backup index.html.before-polish already exists; rename/archive it before running. No files changed.')
shutil.copy2(INDEX, backup)
INDEX.write_text(s, encoding='utf-8')
print('Polished index.html. Backup: index.html.before-polish')
print('Data loaders, charts, and GitHub workflow untouched.')
print('Test locally before committing. Do not add index.html.before-polish to Git.')
